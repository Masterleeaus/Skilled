import assert from 'node:assert/strict';
import {reconcile,audit} from './reconcile-assessment-questions.mjs';
let passed=0;const test=(name,fn)=>{fn();passed++;console.log('PASS',name);};
const q={knowledgeChecks:[{id:'Q1',question:'Question?',options:['A','B','C']}]};
const a={knowledgeAnswers:[{id:'Q1',correctIndex:2}]};
test('valid index and matched question',()=>assert.deepEqual(reconcile(a,q),[]));
test('out of range index rejected',()=>assert(reconcile({knowledgeAnswers:[{id:'Q1',correctIndex:3}]},q).some(f=>f.code==='answer_out_of_range')));
test('negative index rejected',()=>assert(reconcile({knowledgeAnswers:[{id:'Q1',correctIndex:-1}]},q).some(f=>f.code==='answer_out_of_range')));
test('unmatched answer rejected',()=>assert(reconcile({knowledgeAnswers:[{id:'Q2',correctIndex:0}]},q).some(f=>f.code==='unmatched_answer')));
test('unanswered question rejected',()=>assert(reconcile({knowledgeAnswers:[]},q).some(f=>f.code==='question_without_answer')));
test('missing converted source rejected',()=>assert(reconcile(a,null).some(f=>f.code==='missing_converted_lesson')));
test('duplicate question ID rejected',()=>assert(reconcile(a,{knowledgeChecks:[...q.knowledgeChecks,...q.knowledgeChecks]}).some(f=>f.code==='duplicate_question_id')));
test('empty question rejected',()=>assert(reconcile(a,{knowledgeChecks:[{...q.knowledgeChecks[0],question:''}]}).some(f=>f.code==='empty_question')));
test('invalid options rejected',()=>assert(reconcile(a,{knowledgeChecks:[{...q.knowledgeChecks[0],options:['only one']}]}).some(f=>f.code==='invalid_options')));
const report=audit();
test('audits canonical assessments',()=>assert(report.total>300));
test('no implicit approval',()=>assert.equal(report.automaticallyApproved,0));
test('all records have hashes',()=>assert(report.records.every(r=>/^[a-f0-9]{64}$/.test(r.sha256))));
console.log(`${passed} assertions passed`);
