#!/usr/bin/env python3
"""Builds apps/backend/src/modules/levels/course-level-map.json from curriculum/levels/*.csv (PASS42).

Rules:
- The CSV `level` column is authoritative (it already carries overrides). Values: base, group, specialised.
- A row whose `reason` mentions the course map is map-only: the course map placed the lesson there but the
  lesson file does not list that course. Map-only rows are NOT part of that course's gate and are excluded.
- Layer `app` is never gated and never appears in the map.

Usage: python3 -I apps/backend/scripts/build-course-level-map.py <levels-dir> <output-json>
"""
import csv
import glob
import json
import os
import sys
from collections import Counter, defaultdict

LEVELS = {"base", "group", "specialised"}

def main(levels_dir: str, out_path: str) -> None:
    courses: dict[str, dict[str, str]] = defaultdict(dict)
    excluded: Counter = Counter()
    totals: Counter = Counter()
    conflicts = []
    for path in sorted(glob.glob(os.path.join(levels_dir, "*.csv"))):
        if os.path.basename(path) == "ALL-LESSON-LEVELS.csv":
            continue
        with open(path, newline="", encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                slug, lesson, level, reason = row["course_slug"], row["lesson_id"], row["level"], row["reason"]
                totals[slug] += 1
                if "map" in reason.lower():
                    excluded[slug] += 1
                    continue
                if level not in LEVELS:
                    raise SystemExit(f"Unknown level {level!r} in {path}: {lesson}")
                if lesson in courses[slug] and courses[slug][lesson] != level:
                    conflicts.append((slug, lesson))
                courses[slug][lesson] = level
    if conflicts:
        raise SystemExit(f"Conflicting levels for the same course and lesson: {conflicts[:5]}")
    payload = {
        "source": "curriculum/levels/*.csv",
        "note": "Generated by apps/backend/scripts/build-course-level-map.py. Map-only rows excluded.",
        "courses": {slug: dict(sorted(lessons.items())) for slug, lessons in sorted(courses.items())},
    }
    with open(out_path, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    for slug in sorted(totals):
        print(f"{slug}\ttotal={totals[slug]}\tgated={len(courses.get(slug, {}))}\tmap_only_excluded={excluded[slug]}")

if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
